export const dictionaries: Record<Lang, Record<Key, string>> = { en, it };

const initial = (): Lang => {
  const saved = typeof localStorage !== "undefined" ? localStorage.getItem("rg.lang") : null;
  if (saved === "it" || saved === "en") return saved;
  return typeof navigator !== "undefined" && navigator.language.startsWith("it") ? "it" : "en";
};

export const lang = signal<Lang>(initial());

export function setLang(l: Lang): void {
  lang.value = l;
  localStorage.setItem("rg.lang", l);
}

/** Translates a key; `{name}` placeholders are filled from `vars`. */
export function t(key: Key, vars: Record<string, string> = {}): string {
  return dictionaries[lang.value][key].replace(/\{(\w+)\}/g, (_, k: string) => vars[k] ?? `{${k}}`);
}
